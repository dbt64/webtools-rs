async function verifyDirectory(root, directory, identity) {
  const info = await lstat(directory).catch(() => failSource())
  if (!info.isDirectory() || info.isSymbolicLink() || !sameObject(identity, info)) failSource()
  const resolved = await realpath(directory).catch(() => failSource())
  if (!isInside(root, resolved)) failSource()
}

async function cleanupOwned(created) {
  for (const item of created.reverse()) {
    try {
      const current = await lstat(item.path)
      if (item.directory ? !sameObject(item.identity, current) : !sameIdentity(item.identity, current)) continue
      if (item.directory) await rmdir(item.path)
      else await unlink(item.path)
    } catch { /* Preserve replacements and any content not owned by this invocation. */ }
  }
}

async function createDirectory(target, created) {
  try { await mkdir(target, { mode: 0o700 }) }
  catch (error) {
    if (error?.code === 'EEXIST') failExists()
    throw error
  }
  const identity = await lstat(target)
  created.push({ path: target, identity, directory: true })
  return identity
}

async function writeOwnedFile(root, target, targetIdentity, relativeFile, contents, created) {
  await verifyDirectory(root, target, targetIdentity)
  const destination = path.join(target, relativeFile)
  let handle
  try { handle = await open(destination, 'wx', 0o600) }
  catch { failSource() }
  let owned
  try {
    owned = { path: destination, identity: await handle.stat(), directory: false }
    created.push(owned)
    // Revalidate after opening and before writing. This catches a parent or
    // target directory replaced by a junction in the check/open window; the
    // opened file is still empty, so cleanup can remove only this file identity.
    await verifyDirectory(root, target, targetIdentity)
    const [resolvedTarget, resolvedDestination, destinationInfo] = await Promise.all([
      realpath(target).catch(() => failSource()),
      realpath(destination).catch(() => failSource()),
      lstat(destination).catch(() => failSource()),
    ])
    if (!isInside(root, resolvedDestination)
      || path.relative(resolvedTarget, resolvedDestination) !== relativeFile
      || !sameObject(owned.identity, destinationInfo)) failSource()
    await verifyDirectory(root, target, targetIdentity)
    await handle.writeFile(contents, 'utf8')
    await handle.sync()
  } finally {
    if (owned) owned.identity = await handle.stat().catch(() => owned.identity)
    await handle.close()
  }
}

export async function createPluginStarter(directory, options) {
  const segments = safeSegments(directory)
  if (!options || typeof options.hostVersion !== 'string' || !/^[0-9A-Za-z.+-]{1,128}$/.test(options.hostVersion)) failUsage()

  let root
  try { root = await realpath(process.cwd()) } catch { failSource() }
  let parent = root
  for (const segment of segments.slice(0, -1)) {
    parent = path.join(parent, segment)
    let info
    try { info = await lstat(parent) } catch { failUsage() }
    if (!info.isDirectory() || info.isSymbolicLink()) failUsage()
    const resolved = await realpath(parent).catch(() => failSource())
    if (!isInside(root, resolved)) failUsage()
    parent = resolved
  }

  const target = path.join(parent, segments.at(-1))
  try { await lstat(target); failExists() }
  catch (error) { if (error?.code !== 'ENOENT') throw error }

  const targetRelative = segments.join('/')
  const manifest = buildManifest(segments.at(-1), options)
  const slug = slugFor(segments.at(-1))
  const files = generatedFiles(manifest, options.hostVersion, slug)
  const created = []

  try {
    const targetIdentity = await createDirectory(target, created)
    await verifyDirectory(root, target, targetIdentity)
    const dist = path.join(target, 'dist')
    await mkdir(dist, { mode: 0o700 })
    created.push({ path: dist, identity: await lstat(dist), directory: true })

    for (const [relativeFile, contents] of files) {
      await writeOwnedFile(root, target, targetIdentity, relativeFile, contents, created)
    }

    const validated = await validatePluginSourceV1(target, options.hostVersion)
    return { directory: targetRelative, manifest: validated.manifest }
  } catch (error) {
    await cleanupOwned(created)
    if (error instanceof PluginValidationError) throw error
    failSource()
  }
}
