import { createHash } from 'node:crypto'
import { lstat, mkdir, open, realpath, rmdir, unlink } from 'node:fs/promises'
import path from 'node:path'
import { validatePluginSourceV1 } from '../index.mjs'
import { PluginValidationError } from '../runtime/manifest-v1.mjs'

const packageManager = 'pnpm@9.15.9'
const typescriptVersion = '5.9.2'

function failUsage() { throw new PluginValidationError('CLI_USAGE', 'manifest.json') }
function failSource() { throw new PluginValidationError('SOURCE_IO', 'manifest.json') }
function failExists() { throw new PluginValidationError('OUTPUT_EXISTS', 'manifest.json') }

function sameIdentity(left, right) {
  return left.dev === right.dev && left.ino === right.ino && left.size === right.size && left.mtimeMs === right.mtimeMs
}

function sameObject(left, right) { return left.dev === right.dev && left.ino === right.ino }

function isInside(root, candidate) {
  const relative = path.relative(root, candidate)
  return relative === '' || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative))
}

function safeSegments(directory) {
  if (typeof directory !== 'string' || !directory || directory.length > 1024 || path.isAbsolute(directory) || path.win32.isAbsolute(directory) || /^[A-Za-z]:/.test(directory)) failUsage()
  const segments = directory.replaceAll('\\', '/').split('/')
  const safe = []
  for (const segment of segments) {
    if (!segment || segment === '..') failUsage()
    if (segment === '.') continue
    if (segment.length > 200 || /[<>:"|?*\x00-\x1f\x7f]/.test(segment) || /[. ]$/.test(segment) || /^(?:con|prn|aux|nul|com[1-9¹²³]|lpt[1-9¹²³])(?:\.|$)/i.test(segment)) failUsage()
    safe.push(segment)
  }
  if (!safe.length) failUsage()
  return safe
}

function truncateUtf16(value, maxLength) {
  let result = ''
  for (const character of value) {
    if (result.length + character.length > maxLength) break
    result += character
  }
  return result
}

function humanizedName(directoryName) {
  const candidate = directoryName.replace(/[._-]+/g, ' ').replace(/\s+/g, ' ').trim() || 'Basic Plugin'
  return truncateUtf16(candidate, 80)
}

function slugFor(value) {
  const slug = value.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^a-z0-9]+/g, '.').replace(/^\.+|\.+$/g, '').slice(0, 96).replace(/\.+$/g, '')
  return slug || `plugin.${createHash('sha256').update(value, 'utf8').digest('hex').slice(0, 12)}`
}

function buildManifest(directoryName, options) {
  const name = options.name ?? humanizedName(directoryName)
  const slug = slugFor(directoryName)
  return {
    manifestVersion: 1,
    id: options.id ?? `org.example.${slug}`,
    name,
    description: options.description ?? 'A basic WebTools declarative plugin.',
    author: { name: options.author ?? 'Plugin author' },
    version: '1.0.0',
    api: { apiMajor: 1, minHostVersion: options.minHostVersion ?? options.hostVersion },
    type: 'declarative-manager',
    entry: { pageId: 'home', label: name },
    requestedCapabilities: ['manager.page'],
    settings: [],
    pages: [{ id: 'home', title: name, blocks: [{ type: 'heading', text: name }, { type: 'paragraph', text: options.description ?? 'A basic WebTools declarative plugin.' }] }],
    actions: [],
    assets: [],
  }
}

